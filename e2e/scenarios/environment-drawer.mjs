import assert from 'node:assert/strict';

export const environmentDrawerScenario = { id: 'environment-drawer', title: '环境抽屉保留工作区、草稿、焦点与网页录制', async run(t) {
  const p = t.page, info = await t.info();
  const panel = p.locator('.dsh-remote-ops'), drawer = p.locator('.dsh-remote-ops__environmentDrawer');
  const trigger = p.getByRole('button', { name: '环境管理', exact: true });
  const close = () => p.getByRole('button', { name: '关闭环境抽屉', exact: true }).click();
  const call = (path, body) => p.evaluate(async ({path, body}) => {
    const r = await fetch(path, body ? {method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)} : undefined);
    const value = await r.json(); if (!r.ok) throw Error(JSON.stringify(value)); return value;
  }, {path, body});
  const browserApi = body => call('/api/dsh-remote-ops/browser', {sessionId:info.sessionId,...body});
  const snapshot = () => call('/api/dsh-remote-ops/browser?sessionId=' + info.sessionId);
  const until = async fn => { for (let i=0;i<100;i++) { const result=await fn(); if(result)return result; await p.waitForTimeout(100); } throw Error('Drawer state did not settle'); };
  await p.getByRole('button', {name:'Remote Ops',exact:true}).click();
  await p.getByLabel('终端输出', {exact:true}).waitFor();
  // Exercise plugin widths independently of the harness host's sidebar limit.
  await p.addStyleTag({content:'.e2e-sidebar{width:570px;max-width:100%;min-width:0}'});
  await t.step('570px 浮层不改变终端尺寸，Esc 返回入口并保留草稿', async () => {
    const terminal = p.getByLabel('终端输出', {exact:true});
    await terminal.evaluate(node => { window.drawerTestTerminal = node; });
    const before = await p.locator('.dsh-remote-ops__main').boundingBox();
    await trigger.click();
    await drawer.waitFor({state:'visible'});
    await p.waitForTimeout(200);
    assert.deepEqual(await p.locator('.dsh-remote-ops__main').boundingBox(), before);
    assert.equal(Math.round((await drawer.boundingBox()).width), 360);
    assert.equal(await p.getByRole('button',{name:'固定环境抽屉',exact:true}).isVisible(),false);
    assert.equal(await p.getByLabel('搜索 终端环境 环境',{exact:true}).evaluate(node=>document.activeElement===node),true);
    await p.getByRole('button',{name:'+ 环境',exact:true}).click();
    await p.getByLabel('显示名称',{exact:true}).fill('未保存的环境草稿');
    await p.getByLabel('主机地址',{exact:true}).fill('192.0.2.15');
    await p.keyboard.press('Escape');
    assert.equal(await trigger.evaluate(node=>document.activeElement===node),true);
    assert.equal(await terminal.evaluate(node=>node===window.drawerTestTerminal),true);
    assert.doesNotMatch(await terminal.innerText(),/未保存的环境草稿|192\.0\.2\.15/);
    await trigger.click();
    assert.equal(await p.getByLabel('显示名称',{exact:true}).inputValue(),'未保存的环境草稿');
    assert.equal(await p.getByLabel('主机地址',{exact:true}).inputValue(),'192.0.2.15');
    await close();
    assert.ok(await panel.locator('.dsh-remote-ops__head').evaluate(n=>n.getBoundingClientRect().height<=40));
    assert.ok(await panel.locator('.dsh-remote-ops__workspaceTabs').evaluate(n=>n.getBoundingClientRect().height<=37));
  });
  await t.step('宽屏可固定，缩窄自动转浮层，390px 不溢出', async () => {
    await p.setViewportSize({width:1600,height:900});
    await p.addStyleTag({content:'.e2e-sidebar{width:1100px}'});
    await trigger.click();
    await p.getByRole('button',{name:'固定环境抽屉',exact:true}).click();
    await until(async()=>await drawer.getAttribute('data-docked')==='true');
    assert.equal(Math.round((await drawer.boundingBox()).width),320);
    assert.equal(await p.locator('.dsh-remote-ops__main').getAttribute('inert'),null);
    await t.shot('宽屏固定抽屉');
    await p.addStyleTag({content:'.e2e-sidebar{width:570px}'});
    await until(async()=>await drawer.getAttribute('data-docked')==='false');
    assert.equal(Math.round((await drawer.boundingBox()).width),360);
    await t.shot('标准宽度浮层');
    await p.setViewportSize({width:390,height:844});
    await p.addStyleTag({content:'.e2e-sidebar{width:100%;box-sizing:border-box}'});
    await p.emulateMedia({colorScheme:'dark'});
    await until(async()=>Math.round((await drawer.boundingBox()).width)===await panel.evaluate(n=>n.clientWidth));
    assert.ok(await panel.evaluate(n=>n.scrollWidth<=n.clientWidth+1));
    await t.shot('窄屏完整表单');
    await close();
    await p.setViewportSize({width:1280,height:800});
    await p.addStyleTag({content:'.e2e-sidebar{width:570px}'});
    await p.emulateMedia({colorScheme:'light'});
  });
  await t.step('API 抽屉保留请求草稿，关闭后回到原模块', async () => {
    const saved=await call('/e2e/agent',{tool:'remote_api_environment_save',args:{name:'Drawer API fixture',baseUrl:info.website.url,auth:{mode:'none'}}});
    await p.getByRole('tablist',{name:'Remote Ops 工作区'}).getByRole('tab',{name:'API',exact:true}).click();
    await p.getByLabel('API 环境',{exact:true}).selectOption(saved.environment.id);
    await p.getByLabel('API 请求路径',{exact:true}).fill('/unsent-request');
    await trigger.click();
    await p.getByRole('button',{name:'新建 API 环境',exact:true}).click();
    await p.getByLabel('API 环境名称',{exact:true}).fill('API 未保存草稿');
    await p.keyboard.press('Escape');
    assert.equal(await p.getByLabel('API 请求路径',{exact:true}).inputValue(),'/unsent-request');
    await trigger.click();
    assert.equal(await p.getByLabel('API 环境名称',{exact:true}).inputValue(),'API 未保存草稿');
    await close();
  });
  await t.step('抽屉打开期间网页与录制持续，Agent 操作记录可导出', async () => {
    await p.getByRole('tab',{name:'网页',exact:true}).click();
    const browser=(await browserApi({action:'open-url',url:info.website.url+'/manual',display:'embedded',browser:'chrome'})).result;
    await p.getByAltText('网页实时画面',{exact:true}).waitFor();
    const recording=(await browserApi({action:'recording',recording:{action:'start',browserId:browser.id,name:'Drawer continuity'}})).result;
    await p.waitForTimeout(500);
    const before=(await snapshot()).sessions.find(v=>v.id===browser.id);
    const dimensions=await p.locator('.dsh-remote-ops__liveSurface').boundingBox();
    await trigger.click();
    await p.waitForTimeout(250);
    assert.deepEqual(await p.locator('.dsh-remote-ops__liveSurface').boundingBox(),dimensions);
    await call('/e2e/agent',{tool:'remote_browser_run',args:{browserId:browser.id,requestId:'drawer-recording',steps:[{action:'fill',target:{kind:'css',value:'#entry'},value:'During drawer'}]}});
    const after=await until(async()=>{const s=(await snapshot()).sessions.find(v=>v.id===browser.id);return s?.job?.status==='completed'&&s;});
    assert.equal(after.closed,false);assert.equal(after.recording.status,'recording');
    assert.deepEqual(after.pages.map(v=>v.id),before.pages.map(v=>v.id));
    assert.deepEqual(after.viewport,before.viewport);
    await close();
    await p.getByRole('button',{name:'停止网页录制',exact:true}).click();
    const exported=await call('/api/dsh-remote-ops/browser/recording/export?'+new URLSearchParams({sessionId:info.sessionId,recordingId:recording.id}));
    assert.ok(exported.events.some(v=>v.source==='agent'&&v.action==='fill'));
    await browserApi({action:'control',browserId:browser.id,control:'close'});
  });
} };
